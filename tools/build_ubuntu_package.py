"""Build a local Ubuntu package under /opt; building never activates a service."""

import argparse
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PREFIX = Path("/opt/fp-840g5")
PACKAGE = "fp840g5-native"
RELEASE = (ROOT / "VERSION").read_text().strip()
if not re.fullmatch(r"\d+\.\d+\.\d+(?:-alpha\.\d+)?", RELEASE):
    raise SystemExit("Invalid project VERSION")
VERSION = RELEASE.replace("-alpha.", "~alpha")


def run(command, *, cwd=ROOT, env=None):
    command = [str(p) for p in command]
    print("[command] " + shlex.join(command), flush=True)
    subprocess.run(command, cwd=cwd, env=env, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=6)
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    release = dict(
        line.split("=", 1)
        for line in Path("/etc/os-release").read_text().splitlines()
        if "=" in line
    )
    if (
        release.get("ID", "").strip('"') != "ubuntu"
        or release.get("VERSION_ID", "").strip('"') != "26.04"
    ):
        raise SystemExit("Build this package on the Ubuntu 26.04 target")
    architecture = subprocess.check_output(["dpkg", "--print-architecture"], text=True).strip()
    if architecture != "amd64":
        raise SystemExit("This validated target is amd64")
    source = ROOT / "sources/libfprint-vcsfw"
    lock = json.loads((ROOT / "sources.lock.json").read_text())
    head = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    patch = ROOT / "patches/libfprint-hp840g5.patch"
    actual_diff = subprocess.check_output(["git", "-C", str(source), "diff", "--binary"])
    if head != lock["libfprint"]["commit"] or actual_diff != patch.read_bytes():
        raise SystemExit("Source revision and complete local diff must match the pinned patch")
    build = ROOT / "build/package-libfprint"
    configure = [
        "meson",
        "setup",
        build,
        source,
        "--prefix",
        PREFIX,
        "--libdir",
        "lib",
        "--buildtype",
        "release",
        "-Ddrivers=validity",
        "-Ddoc=false",
        "-Dintrospection=false",
        "-Dgtk-examples=false",
        "-Dinstalled-tests=false",
        "-Dudev_rules=disabled",
        "-Dudev_hwdb=disabled",
    ]
    configure.append("-Dc_args=" + json.dumps([f"-ffile-prefix-map={ROOT}=."]))
    if (build / "meson-private/coredata.dat").exists():
        configure.append("--reconfigure")
    run(configure)
    run(["meson", "compile", "-C", build, "-j", args.jobs])
    run(["meson", "test", "-C", build, "--suite", "unit-tests", "--print-errorlogs"])
    output = ROOT / "build" / f"{PACKAGE}_{VERSION}_{architecture}.deb"
    with tempfile.TemporaryDirectory(prefix="ubuntu-package-", dir=ROOT / "build") as temporary:
        working = Path(temporary)
        destination = working / "root"
        run(["meson", "install", "-C", build, "--no-rebuild", "--destdir", destination])
        installed = destination / PREFIX.relative_to("/")
        # Public packages contain open-source code only. Runtime vendor data is
        # fetched/generated by each user and installed separately, never bundled.
        vendor_data = installed / "share/libfprint/validity"
        if vendor_data.exists():
            raise SystemExit("Unexpected vendor data in Meson install; refusing a public package")
        include = [
            f"-I{build}",
            f"-I{build / 'libfprint'}",
            f"-I{source}",
            f"-I{source / 'libfprint'}",
        ]
        flags = shlex.split(
            subprocess.check_output(
                ["pkg-config", "--cflags", "--libs", "gio-2.0", "gusb"], text=True
            )
        )
        run(
            [
                "cc",
                "-shared",
                "-fPIC",
                "-Wall",
                "-Wextra",
                "-Werror",
                *include,
                f"-ffile-prefix-map={ROOT}=.",
                ROOT / "tools/preserve_prints.c",
                "-o",
                installed / "lib/preserve-prints.so",
                f"-L{installed / 'lib'}",
                "-lfprint-2",
                "-ldl",
                f"-Wl,-rpath,{PREFIX / 'lib'}",
                *flags,
            ]
        )
        doc = destination / "usr/share/doc" / PACKAGE
        doc.mkdir(parents=True)
        shutil.copy2(source / "COPYING", doc / "COPYING.libfprint")
        shutil.copy2(ROOT / "LICENSE", doc / "LICENSE")
        shutil.copy2(ROOT / "NOTICE.md", doc / "NOTICE.md")
        shutil.copy2(ROOT / "sources.lock.json", doc / "sources.lock.json")
        shutil.copy2(patch, doc / patch.name)
        (doc / "fprintd.conf").write_text(
            "[Service]\nEnvironment=LD_LIBRARY_PATH=/opt/fp-840g5/lib\n"
            "Environment=FP_DRIVERS_ALLOWLIST=validity\n"
            "UnsetEnvironment=FP_DEVICE_EMULATION G_MESSAGES_DEBUG\n"
        )
        (doc / "preserve-existing.conf").write_text(
            "[Service]\nEnvironment=LD_PRELOAD=/opt/fp-840g5/lib/preserve-prints.so\n"
            "Environment=FP840G5_ALLOW_NATIVE_PRINT_DELETE=1\n"
        )
        (doc / "README").write_text(
            "Experimental native driver for HP EliteBook 840 G5 / 138a:00ab.\n"
            "Installing the archive does not change service or PAM configuration.\n"
            "The supplied fprintd.conf can activate the private library after hardware checks.\n"
            "preserve-existing.conf permits native print management and protects foreign records.\n"
            "No vendor firmware/data, user templates or pairing material are included.\n"
            "Vendor data must be obtained separately under its own terms.\n"
        )
        debian = working / "debian"
        debian.mkdir()
        (debian / "control").write_text(
            f"Source: {PACKAGE}\nSection: admin\nPriority: optional\n"
            "Maintainer: Saatvik Sharma <75624562+saatvik333@users.noreply.github.com>\n\n"
            f"Package: {PACKAGE}\nArchitecture: amd64\n"
            "Description: Local native Validity driver\n"
        )
        dependency_output = subprocess.check_output(
            ["dpkg-shlibdeps", "-O", str(installed / "lib/libfprint-2.so.2.0.0")],
            cwd=working,
            text=True,
        )
        dependencies = next(
            line.partition("=")[2]
            for line in dependency_output.splitlines()
            if line.startswith("shlibs:Depends=")
        )
        control = destination / "DEBIAN"
        control.mkdir()
        (control / "control").write_text(
            f"Package: {PACKAGE}\nVersion: {VERSION}\nArchitecture: {architecture}\n"
            "Section: admin\nPriority: optional\n"
            "Maintainer: Saatvik Sharma <75624562+saatvik333@users.noreply.github.com>\n"
            f"Depends: fprintd (>= 1.94.5), {dependencies}\n"
            "Description: Locally built native driver for HP EliteBook 840 G5\n"
            " Open-source private libfprint and preservation guard; vendor data is separate.\n"
        )
        loader_env = dict(os.environ, LD_BIND_NOW="1", LD_LIBRARY_PATH=str(installed / "lib"))
        run(["/usr/libexec/fprintd", "--help"], env=loader_env)
        hashes = {
            str(p.relative_to(destination)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in installed.rglob("*")
            if p.is_file() and not p.is_symlink()
        }
        (doc / "manifest.json").write_text(
            json.dumps(
                {
                    "source_commit": head,
                    "patch_sha256": hashlib.sha256(actual_diff).hexdigest(),
                    "vendor_data_included": False,
                    "project_release": RELEASE,
                    "files": hashes,
                },
                indent=2,
            )
            + "\n"
        )
        run(["dpkg-deb", "--root-owner-group", "--build", destination, output])
        run(["dpkg-deb", "--info", output])
        from audit_package import audit_package

        audit_package(output)
    output.with_suffix(".deb.sha256").write_text(
        hashlib.sha256(output.read_bytes()).hexdigest() + "  " + output.name + "\n"
    )
    print(f"[verified] Local package built without activating any service: {output}", flush=True)


if __name__ == "__main__":
    main()
